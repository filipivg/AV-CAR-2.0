    private void carregarFuncoes() {
        funcoesList = funcaoController.listarAtivos();
        DefaultListModel<String> model = new DefaultListModel<>();
        for (Funcao f : funcoesList) {
            model.addElement(f.getDescricao());
        }
        ListColaboradores.setModel(model);
        ListColaboradores.setSelectionMode(ListSelectionModel.MULTIPLE_INTERVAL_SELECTION);

        List<ColaboradorFuncao> funcoesAtuais = colaboradorController.listarFuncoesDoColaborador(colaborador.getID());
        for (ColaboradorFuncao cf : funcoesAtuais) {
            for (int i = 0; i < funcoesList.size(); i++) {
                if (funcoesList.get(i).getID() == cf.getFuncao().getID()) {
                    ListColaboradores.addSelectionInterval(i, i);
                }
            }
        }
    }
    
