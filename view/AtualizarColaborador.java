    private void BntAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BntAtualizarActionPerformed
        String nome = TxFNome.getText().trim();

        if (ListColaboradores.getSelectedIndices().length == 0) {
            JOptionPane.showMessageDialog(null, "Selecione pelo menos uma função.");
            return;
        }

        colaborador.setNome(nome);
        colaboradorController.atualizar(colaborador);

        List<ColaboradorFuncao> funcoesAtuais = colaboradorController.listarFuncoesDoColaborador(colaborador.getID());
        for (ColaboradorFuncao cf : funcoesAtuais) {
            colaboradorController.desvincularFuncao(colaborador.getID(), cf.getFuncao().getID());
        }

        for (int i : ListColaboradores.getSelectedIndices()) {
            ColaboradorFuncao cf = new ColaboradorFuncao(colaborador, funcoesList.get(i));
            colaboradorController.vincularFuncao(cf);
        }

        JOptionPane.showMessageDialog(null, "Colaborador atualizado com sucesso!");

        TxFNome.setText("");
        ListColaboradores.clearSelection();
    }//GEN-LAST:event_BntAtualizarActionPerformed

